import assert from 'node:assert/strict';
import { mergeExtractionImages } from '../src/lib/extractionImageIdentity.ts';
import { mergeExtractionFonts } from '../src/lib/extractionFontIdentity.ts';
import { getImageDisplayName, imageFilenameBase } from '../src/lib/imageAsset.ts';
import { getFontSelectionKey } from '../src/lib/fontAsset.ts';
import { resolveDuplicateImageContent } from '../server/duplicate-image-content.ts';
const image = (path, extra = {}) => ({url: `https://example.com/${path}`, ...extra});
const largest = mergeExtractionImages([image('photo.jpg?w=96',{width:96,cachedUrl:'/tiny'}),image('photo.jpg?w=1600',{width:1600})]);
assert.equal(largest.length,1);
assert.equal(largest[0].width,1600);
const distinct=mergeExtractionImages([image('a/photo.jpg'),image('b/photo.jpg')]);
assert.equal(distinct.length,2);
assert.equal(new Set(distinct.map(getImageDisplayName)).size,2);
assert.equal(new Set(distinct.map(imageFilenameBase)).size,2);
assert.deepEqual(mergeExtractionImages(distinct),distinct);
const equal=await resolveDuplicateImageContent([image('a/photo.jpg',{width:100}),image('b/photo.jpg',{width:500})],async()=>Buffer.from('same original'));
assert.equal(mergeExtractionImages(equal).length,1);
assert.equal(mergeExtractionImages(equal)[0].width,500);
assert.equal(mergeExtractionImages([image('sprite.svg#a'),image('sprite.svg#b')]).length,2);
assert.equal(mergeExtractionImages([image('photo.jpg?crop=left'),image('photo.jpg?crop=right')]).length,2);
assert.equal(mergeExtractionImages([image('frame1.jpg',{sequenceFrame:1,contentHash:'same'}),image('frame2.jpg',{sequenceFrame:2,contentHash:'same'})]).length,2);
const fonts=mergeExtractionFonts([{url:'https://x/a.woff',family:'Example',weight:400},{url:'https://x/b.woff2',family:'example',weight:400},{url:'https://x/c.woff2',family:'Example-BoldItalic',style:'normal'},{url:'https://x/d.woff2',family:'Example',weight:700,style:'italic'}]);
assert.equal(fonts.length,2);
assert.notEqual(getFontSelectionKey({url:'https://x/font.woff2',weight:400}),getFontSelectionKey({url:'https://x/font.woff2',weight:700}));
assert.equal(mergeExtractionFonts([{url:'https://x/a.woff2',family:'Example',weight:400},{url:'https://x/a.woff2',family:'Example',weight:700}]).length,2);
console.log('Extraction dedup regression passed');
